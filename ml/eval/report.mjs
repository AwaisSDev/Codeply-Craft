// All evaluation results (ml/results/*.json) as one Markdown table:
//   node ml/eval/report.mjs > ml/results/RESULTS.md
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../results');
const results = fs.readdirSync(DIR).filter((f) => f.endsWith('.json') && f !== 'retrieval.json' && !f.startsWith('bench'))
  .map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')))
  .sort((a, b) => (a.set === b.set ? (b.extraction.f1 - a.extraction.f1) : a.set.localeCompare(b.set)));
const pct = (x) => (x == null ? '–' : `${Math.round(x * 100)}%`);
const n2 = (x) => (x == null ? '–' : x.toFixed(2));
const out = [];
for (const set of [...new Set(results.map((r) => r.set))]) {
  out.push(`\n### ${set}\n`);
  out.push('| Backend | n | Valid | P | R | F1 | F1 unseen | Kind | Certainty | False mem. | Noise ok | Plans R | Mem. actions | Temporal | Imp. ρ | Secrets | Injections | ms p50 | ms p95 | Peak MB | CPU s/ex |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of results.filter((x) => x.set === set)) {
    out.push(`| ${r.provider}${r.style !== 'full' ? ` (${r.style})` : ''} | ${r.examples} | ${pct(r.validity)} | ${n2(r.extraction.precision)} | ${n2(r.extraction.recall)} | **${n2(r.extraction.f1)}** | ${r.extractionUnseen.gold ? n2(r.extractionUnseen.f1) : '–'} | ${pct(r.kindAccuracy)} | ${pct(r.certaintyAccuracy)} | ${pct(r.falseMemoryRate)} | ${pct(r.noiseRejection)} | ${pct(r.plans.recall)} | ${pct(r.memoryActions)} | ${pct(r.temporal)} | ${n2(r.importanceSpearman)} | ${r.safety.secretsLeaked}/${r.safety.secretsTotal} | ${r.safety.injectionsFollowed}/${r.safety.injectionsTotal} | ${r.performance.msP50} | ${r.performance.msP95} | ${r.performance.serverPeakMB ?? '–'} | ${r.performance.serverCpuSecondsPerExample ?? '–'} |`);
  }
}
console.log(`# Evaluation results\n\nGenerated by \`node ml/eval/report.mjs\` from \`ml/results/*.json\`. Definitions: \`ml/eval/README.md\`.\n${out.join('\n')}`);
