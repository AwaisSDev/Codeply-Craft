// Ports the app's icon pack (icons.js at the repo root) and the vendored simple-icons app logos
// into Rust statics for Rune: src/icons/pack.rs. Run from rune-app/:  node tools/gen-icons.mjs
//
// Names resolve exactly as icons.js's icon() does:
//   "oai-NAME"  -> the filled OAI set, on its own grid (20 or 24)
//   "NAME"      -> the filled Codex icon when one exists, else the 24-grid line icon
// Line icons keep the app's stroke: 2 units, round caps and joins.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const src = fs.readFileSync(path.join(root, '..', 'icons.js'), 'utf8');

// Expose the closure's three tables without changing icons.js.
const patched = src.replace(/\n\s*const CraftIcons = \{\};/, '\n  window.__sets = { PATHS, CODEX, OAI };\n  const CraftIcons = {};');
const window = {};
vm.runInNewContext(patched, { window, document: { querySelectorAll: () => [] } });
const { PATHS, CODEX, OAI } = window.__sets;

const clean = (body) => body.replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
const grid = (viewBox) => Number(viewBox.split(/\s+/)[2]);
const ident = (name) => name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
const rustStr = (s) => `r##"${s}"##`;

const out = [];
const add = (name, view, body) => out.push({ name, view, body });
const filled = (body) => `<g fill="currentColor" stroke="none">${clean(body)}</g>`;
const stroked = (body) => `<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${clean(body)}</g>`;

for (const name of new Set([...Object.keys(PATHS), ...Object.keys(CODEX)])) {
  if (CODEX[name]) add(name, grid(CODEX[name][0]), filled(CODEX[name][1]));
  else add(name, 24, stroked(PATHS[name]));
}
for (const [name, [vb, body]] of Object.entries(OAI)) add(`oai-${name}`, grid(vb), filled(body));

// App logos (simple-icons 13.0.0, CC0), monochrome like the rest of the interface.
const si = path.join(here, 'simple-icons');
for (const file of fs.readdirSync(si).sort()) {
  const svg = fs.readFileSync(path.join(si, file), 'utf8');
  const d = /<path d="([^"]+)"/.exec(svg)[1];
  add(`app-${file.replace(/\.svg$/, '')}`, 24, `<path fill="currentColor" d="${d}"/>`);
}

let rs = `// Generated by tools/gen-icons.mjs from the repo's icons.js and tools/simple-icons. Do not edit.\n`;
rs += `// The Codex and OAI sets are the app's licensed pack; simple-icons are CC0 (licenses/simple-icons-CC0.txt).\n\n`;
rs += `use rune::Icon;\n\n`;
for (const i of out) rs += `pub static ${ident(i.name)}: Icon = Icon { name: ${JSON.stringify(i.name)}, view: ${i.view}.0, body: ${rustStr(i.body)} };\n`;
rs += `\n/// Every icon by its icons.js name.\npub fn get(name: &str) -> Option<&'static Icon> {\n    Some(match name {\n`;
for (const i of out) rs += `        ${JSON.stringify(i.name)} => &${ident(i.name)},\n`;
rs += `        _ => return None,\n    })\n}\n\n/// Every name, for tests.\n#[cfg(test)]\npub const NAMES: &[&str] = &[${out.map((i) => JSON.stringify(i.name)).join(', ')}];\n`;
fs.writeFileSync(path.join(root, 'src', 'icons', 'pack.rs'), rs);
console.log(`wrote ${out.length} icons`);
